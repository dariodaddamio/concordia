# Measures the release binary and the draw loop, writes docs/metrics.md and prints JSON.
# Reproduce:  powershell -NoProfile -File scripts\metrics.ps1
# Only measured values are written. Idle memory is not measured.
param([int]$Runs = 30)
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

cargo build --release --locked -p concordia
if ($LASTEXITCODE -ne 0) { throw "release build failed" }
$exe = Join-Path $root "target\release\concordia.exe"
$sizeKb = [math]::Round((Get-Item $exe).Length / 1KB, 0)

# Cold start of `concordia --version`: spawn to exit, wall clock, includes process creation.
$null = & $exe --version
$versionLine = (& $exe --version | Select-Object -First 1).Trim()
$ms = New-Object System.Collections.Generic.List[double]
for ($i = 0; $i -lt $Runs; $i++) {
    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName = $exe; $psi.Arguments = "--version"
    $psi.UseShellExecute = $false; $psi.RedirectStandardOutput = $true; $psi.CreateNoWindow = $true
    $sw = [System.Diagnostics.Stopwatch]::StartNew()
    $p = [System.Diagnostics.Process]::Start($psi)
    $null = $p.StandardOutput.ReadToEnd()
    $p.WaitForExit()
    $sw.Stop()
    $p.Dispose()
    $ms.Add($sw.Elapsed.TotalMilliseconds)
}
$sorted = $ms | Sort-Object
$median = if ($Runs % 2) { $sorted[($Runs - 1) / 2] } else { ($sorted[$Runs / 2 - 1] + $sorted[$Runs / 2]) / 2 }
$p95 = $sorted[[math]::Min($Runs - 1, [int][math]::Ceiling($Runs * 0.95) - 1)]

# draw_ui over 500 frames (release test profile).
$ErrorActionPreference = "Continue"   # cargo writes progress to stderr
$out = cmd /c "cargo test --release -p concordia --lib screenshots::bench_draw_ui -- --ignored --nocapture 2>&1" | Out-String
$ErrorActionPreference = "Stop"
$m = [regex]::Match($out, 'DRAW_UI_BENCH frames=(\d+) size=(\d+x\d+) mean_us=([\d.]+) p95_us=(\d+)')
if (-not $m.Success) { throw "bench line not found:`n$out" }
$frames = [int]$m.Groups[1].Value; $size = $m.Groups[2].Value
$meanUs = [double]$m.Groups[3].Value; $p95Us = [int]$m.Groups[4].Value

$cpu = (Get-CimInstance Win32_Processor | Select-Object -First 1).Name.Trim()
$date = Get-Date -Format "yyyy-MM-dd"
$stamp = if ($versionLine -match '\(([^)]+)\)') { $Matches[1] } else { $versionLine }

$result = [ordered]@{
    date = $date; build_stamp = $stamp; cpu = $cpu; os = "Windows 11"
    binary_kb = $sizeKb
    cold_start_runs = $Runs
    cold_start_median_ms = [math]::Round($median, 1)
    cold_start_p95_ms = [math]::Round($p95, 1)
    draw_frames = $frames; draw_size = $size
    draw_mean_us = [math]::Round($meanUs, 1)
    draw_p95_us = $p95Us
}

$md = @"
# Metrics

Generated by ``scripts/metrics.ps1`` (do not edit by hand). Measured on $cpu, Windows 11, $date, build $stamp.

| Metric | Value |
| --- | --- |
| Release binary size | $sizeKb KB |
| Cold start, ``concordia --version`` (median of $Runs runs) | $([math]::Round($median, 1)) ms |
| Cold start, ``concordia --version`` (p95 of $Runs runs) | $([math]::Round($p95, 1)) ms |
| ``draw_ui`` frame, busy transcript, $size (mean of $frames frames) | $([math]::Round($meanUs, 0)) us |
| ``draw_ui`` frame, busy transcript, $size (p95 of $frames frames) | $p95Us us |

Cold start is wall-clock time from spawning the process to its exit, including process creation.
The draw time is ``draw_ui`` on a ratatui ``TestBackend`` with a synthetic conversation, measured by
the ignored test ``tui::screenshots::bench_draw_ui`` in the release test profile. Idle memory is not measured.

Reproduce: ``powershell -NoProfile -File scripts\metrics.ps1``
"@
Set-Content -Path (Join-Path $root "docs\metrics.md") -Value $md -Encoding utf8
$result | ConvertTo-Json
